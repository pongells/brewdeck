#!/usr/bin/env python3
"""Renders the offline screen's cup (full with crema / empty and grey) into firmware/src/ui/screens/cup_art.h.

LVGL draws no ellipses, so the cup and saucer are small pre-rendered RGB565 pictures on the tile's colour (COL_CARD);
the steam above the cup is drawn live (offline.cpp), so it can rise and fade. The geometry is on a 96-unit grid (the
logo's grid), drawn into the 112 px tile, antialiased by rendering 8x larger and scaling down.

Usage (repo root): python3 tools/gen_cup.py     (needs Pillow)
"""
import os
from PIL import Image, ImageDraw

TILE = 112                     # px, the offline icon tile
K = TILE / 96.0                # grid unit -> px
SS = 8                         # supersampling
X0, Y0, W, H = 12, 38, 88, 62  # the part of the tile the picture covers (px)
CARD = (0x1A, 0x1A, 0x1D)

STYLES = {   # line, body, inside of the cup
    'full': ((0xC9, 0xC9, 0xCF), (0x2C, 0x2C, 0x31), (0xB9, 0x7A, 0x3E)),
    'empty': ((0x5E, 0x5E, 0x66), (0x1F, 0x1F, 0x23), (0x12, 0x12, 0x14)),
}


def px(x, y):                  # grid -> supersampled picture coordinates
    return ((x * K - X0) * SS, (y * K - Y0) * SS)


def bez(p0, p1, p2, p3, n=48):
    out = []
    for i in range(n + 1):
        u = i / n
        v = 1 - u
        out.append(tuple(v * v * v * a + 3 * v * v * u * b + 3 * v * u * u * c + u * u * u * d
                         for a, b, c, d in zip(p0, p1, p2, p3)))
    return out


def stroke(d, pts, col, w):
    w = w * K * SS
    d.line([px(*p) for p in pts], fill=col, width=int(round(w)), joint='curve')
    for p in (pts[0], pts[-1]):                     # round caps
        x, y = px(*p)
        d.ellipse((x - w / 2, y - w / 2, x + w / 2, y + w / 2), fill=col)


def ellipse(d, cx, cy, rx, ry, fill, line=None, w=0):
    w = w * K * SS
    x0, y0 = px(cx - rx, cy - ry)
    x1, y1 = px(cx + rx, cy + ry)
    d.ellipse((x0 - w / 2, y0 - w / 2, x1 + w / 2, y1 + w / 2), fill=fill, outline=line, width=int(round(w)))


def cup(style):
    line, body, inside = STYLES[style]
    img = Image.new('RGB', (W * SS, H * SS), CARD)
    d = ImageDraw.Draw(img, 'RGBA')
    ellipse(d, 48, 74, 35, 7.5, (0x20, 0x20, 0x24), line, 3)                     # saucer
    stroke(d, bez((72, 48), (85, 46), (85, 64), (68, 63)), line, 3.4)            # handle
    side = bez((22, 42), (22, 60), (31, 71), (47, 71)) + bez((47, 71), (63, 71), (72, 60), (72, 42))[1:]
    d.polygon([px(*p) for p in side], fill=body)                                 # body
    stroke(d, side, line, 3.2)
    ellipse(d, 47, 42, 25, 6.5, inside, line, 3.2)                               # rim + crema / empty inside
    if style == 'full':
        ellipse(d, 47, 42.5, 16, 3, (0xD9, 0x9A, 0x58, 140))                    # lighter crema in the middle
    return img.resize((W, H), Image.LANCZOS)


def rgb565(img):
    out = []
    for r, g, b in zip(*[iter(img.tobytes())] * 3):
        out.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    return out


def main():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    path = os.path.join(root, 'firmware', 'src', 'ui', 'screens', 'cup_art.h')
    s = ['// Generated by tools/gen_cup.py: the offline screen\'s cup, RGB565 on COL_CARD. Do not edit.',
         '#pragma once', '#include <stdint.h>', '',
         'static const int CUP_X = %d, CUP_Y = %d, CUP_W = %d, CUP_H = %d;   // place in the 112 px tile' % (X0, Y0, W, H)]
    for name in ('full', 'empty'):
        v = rgb565(cup(name))
        s.append('static const uint16_t CUP_%s[%d] = {' % (name.upper(), len(v)))
        for i in range(0, len(v), 16):
            s.append('  ' + ', '.join('0x%04X' % x for x in v[i:i + 16]) + ',')
        s.append('};')
    open(path, 'w').write('\n'.join(s) + '\n')
    print('wrote', os.path.relpath(path, root))


if __name__ == '__main__':
    main()
